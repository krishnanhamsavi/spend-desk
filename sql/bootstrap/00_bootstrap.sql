-- Spend Desk bootstrap. Run once as ACCOUNTADMIN.
-- Creates the project role, a capped XSMALL warehouse, and the database layout.
-- Replace <YOUR_USER> before running.

USE ROLE ACCOUNTADMIN;

-- 1. Resource monitor. Hard cap on trial spend, reset monthly.
CREATE RESOURCE MONITOR IF NOT EXISTS SPEND_DESK_RM
  WITH CREDIT_QUOTA = 25
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 50 PERCENT DO NOTIFY
    ON 75 PERCENT DO NOTIFY
    ON 90 PERCENT DO SUSPEND
    ON 100 PERCENT DO SUSPEND_IMMEDIATE;

-- 2. Warehouse. Smallest size, suspends after 60 seconds idle, kills runaway queries.
CREATE WAREHOUSE IF NOT EXISTS SPEND_DESK_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 600
  COMMENT = 'Spend Desk portfolio project';

ALTER WAREHOUSE SPEND_DESK_WH SET RESOURCE_MONITOR = SPEND_DESK_RM;

-- 3. Project role, granted to the developer user.
CREATE ROLE IF NOT EXISTS SPEND_DESK_ROLE;
GRANT ROLE SPEND_DESK_ROLE TO ROLE SYSADMIN;
GRANT ROLE SPEND_DESK_ROLE TO USER <YOUR_USER>;
GRANT USAGE, OPERATE ON WAREHOUSE SPEND_DESK_WH TO ROLE SPEND_DESK_ROLE;

-- Cortex AI functions (used from Phase 6 onward).
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE SPEND_DESK_ROLE;

-- 4. Database and schemas, owned by the project role.
CREATE DATABASE IF NOT EXISTS SPEND_DESK COMMENT = 'Synthetic data shaped like ACCOUNT_USAGE. Not real usage.';
GRANT OWNERSHIP ON DATABASE SPEND_DESK TO ROLE SPEND_DESK_ROLE COPY CURRENT GRANTS;

USE ROLE SPEND_DESK_ROLE;
USE DATABASE SPEND_DESK;
CREATE SCHEMA IF NOT EXISTS RAW  COMMENT = 'Synthetic source tables and ground truth';
CREATE SCHEMA IF NOT EXISTS CORE COMMENT = 'Cleaned, conformed models';
CREATE SCHEMA IF NOT EXISTS MART COMMENT = 'Precomputed outputs read by the app';
CREATE SCHEMA IF NOT EXISTS APP  COMMENT = 'Streamlit app, stages, agent logs';

-- 5. Verify.
SHOW WAREHOUSES LIKE 'SPEND_DESK_WH';
SHOW RESOURCE MONITORS LIKE 'SPEND_DESK_RM';
SHOW SCHEMAS IN DATABASE SPEND_DESK;
